package com.voxelforge.core.world

import com.voxelforge.core.block.Blocks

/**
 * Абстракция чтения вокселей.
 *
 * Назначение: развязать потребителей данных мира от способа их хранения.
 * Читателей три, и у каждого свой источник:
 *  - физика и трассировка луча читают живой [World];
 *  - мешер читает неизменяемый снимок 3×3 чанков (см. ChunkNeighborhood),
 *    чтобы работать в фоновом потоке, не боясь одновременных изменений;
 *  - генератор структур читает чанк, который ещё не опубликован.
 *
 * Это применение принципа инверсии зависимостей: мешер зависит от узкого
 * интерфейса, а не от класса World со всей его машинерией загрузки, потоков
 * и сохранения. Побочный, но важный эффект — мешер тестируется на JVM
 * подстановкой массива-заглушки.
 */
interface BlockAccess {

    /**
     * Идентификатор блока в мировых координатах.
     * За пределами мира по вертикали обязан вернуть [Blocks.AIR],
     * а для незагруженного чанка — значение, при котором грань на границе
     * загруженной области **не** строится (иначе на краю мира видна стена).
     */
    fun getBlock(x: Int, y: Int, z: Int): Int

    /** Солнечная освещённость 0..15. */
    fun getSkyLight(x: Int, y: Int, z: Int): Int

    /** Освещённость от источников 0..15. */
    fun getBlockLight(x: Int, y: Int, z: Int): Int

    /** Идентификатор биома в колонке — нужен мешеру для тонирования травы и листвы. */
    fun getBiome(x: Int, z: Int): Int

    /** Высота верхнего непрозрачного блока в колонке (для погоды и спавна). */
    fun getHeight(x: Int, z: Int): Int

    // --- Производные операции с реализацией по умолчанию ---

    fun isAir(x: Int, y: Int, z: Int): Boolean = getBlock(x, y, z) == Blocks.AIR

    fun isSolid(x: Int, y: Int, z: Int): Boolean = Blocks.SOLID[getBlock(x, y, z)]

    fun isLiquid(x: Int, y: Int, z: Int): Boolean = Blocks.LIQUID[getBlock(x, y, z)]

    /**
     * Совокупная освещённость для затенения вершины.
     * Берётся максимум, а не сумма: факел под открытым небом не должен
     * пересвечивать поверхность до значения выше максимального.
     */
    fun getCombinedLight(x: Int, y: Int, z: Int): Int =
        maxOf(getSkyLight(x, y, z), getBlockLight(x, y, z))
}
