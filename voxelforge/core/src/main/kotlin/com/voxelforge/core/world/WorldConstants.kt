package com.voxelforge.core.world

/**
 * Геометрические константы мира.
 *
 * Назначение: единственное место, где заданы размеры чанка и высота мира.
 * Все они — степени двойки, и это не эстетика, а требование производительности:
 * перевод мировых координат в локальные выполняется сдвигом и маской
 * (`x shr 4`, `x and 15`) вместо деления и остатка. В мешере такой перевод
 * происходит на каждом вокселе, а целочисленное деление на ARM стоит
 * порядка 20 тактов против одного такта на сдвиг.
 */
object WorldConstants {

    /** Сторона секции. 16 — компромисс: меньше даёт слишком много вызовов
     *  отрисовки, больше — слишком долгую перестройку меша при ломке блока. */
    const val SECTION_SIZE = 16
    const val SECTION_SHIFT = 4
    const val SECTION_MASK = SECTION_SIZE - 1

    /** Число вокселей в секции: 16³. */
    const val SECTION_VOLUME = SECTION_SIZE * SECTION_SIZE * SECTION_SIZE

    /** Число секций по вертикали в колонке чанка. */
    const val SECTIONS_PER_CHUNK = 8

    /**
     * Полная высота мира — 128 блоков.
     *
     * Выбор под мобильную платформу. При 256 блоках объём данных и, главное,
     * объём мешинга удваиваются, а верхняя половина в реальном ландшафте почти
     * всегда пустая. 128 блоков дают горы высотой около 60 метров над уровнем
     * моря — визуально этого достаточно, а бюджет памяти сокращается вдвое.
     */
    const val WORLD_HEIGHT = SECTION_SIZE * SECTIONS_PER_CHUNK

    const val MAX_Y = WORLD_HEIGHT - 1

    /** Площадь основания чанка — размер карт высот и биомов. */
    const val CHUNK_AREA = SECTION_SIZE * SECTION_SIZE

    /** Уровень моря: ниже него впадины заполняются водой. */
    const val SEA_LEVEL = 54

    /** Верхняя граница слоя коренной породы. */
    const val BEDROCK_TOP = 2

    /** Максимальный уровень освещённости. 15 умещается в полубайт. */
    const val MAX_LIGHT = 15

    /**
     * Индекс вокселя внутри секции.
     *
     * Порядок Y→Z→X выбран под мешер: он обходит воксели построчно вдоль X,
     * и при такой раскладке соседние по X элементы лежат подряд в памяти.
     * Это даёт последовательное чтение кэш-линий вместо прыжков по массиву —
     * на практике перестройка секции ускоряется примерно на треть.
     */
    inline fun sectionIndex(x: Int, y: Int, z: Int): Int =
        (y shl 8) or (z shl 4) or x

    /** Индекс в картах высот и биомов (16×16). */
    inline fun columnIndex(x: Int, z: Int): Int = (z shl 4) or x

    /** Мировая координата блока → координата чанка. */
    inline fun blockToChunk(v: Int): Int = v shr SECTION_SHIFT

    /** Мировая координата блока → локальная внутри чанка (всегда 0..15). */
    inline fun blockToLocal(v: Int): Int = v and SECTION_MASK
}
